"""Export the canonical Pydantic contracts to JSON Schema.

Usage (from the repository root, inside the project virtualenv):
    python scripts/gen_contracts.py            # rewrite packages/contracts/schemas/contracts.schema.json
    python scripts/gen_contracts.py --check    # exit 1 if the committed schema is out of date

TypeScript types are generated from the JSON Schema by the web workspace
(`npm run contracts`, json-schema-to-typescript), wired up in Chunk 1.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages" / "contracts" / "python"))

from pydantic.json_schema import models_json_schema  # noqa: E402

from greality_contracts import CONTRACT_VERSION, EXPORTED  # noqa: E402

OUT = ROOT / "packages" / "contracts" / "schemas" / "contracts.schema.json"


def build() -> str:
    _, schema = models_json_schema([(m, "serialization") for m in EXPORTED], title="G-reality contracts")
    schema["$comment"] = "GENERATED by scripts/gen_contracts.py from greality_contracts/models.py. Do not edit."
    schema["x-contract-version"] = CONTRACT_VERSION
    return json.dumps(schema, indent=2, sort_keys=True) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("contracts.schema.json is out of date; run scripts/gen_contracts.py", file=sys.stderr)
            return 1
        print("contracts.schema.json is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
