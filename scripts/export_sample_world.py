"""Write apps/web/public/sample-world.json: a read-only snapshot for offline viewing and visual tests.

    .venv\\Scripts\\python scripts\\export_sample_world.py

Built with the same code paths as the live service (rules interpreter → build_spec → generate_region),
but without the database, so it is deterministic and needs no network. It is a *snapshot*: the web app
labels it as offline and cannot commit changes to it.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "services"), str(ROOT / "packages" / "contracts" / "python")]

from greality_contracts import (  # noqa: E402
    Condition,
    GameplayState,
    GenerationStatus,
    PlayerState,
    RegionCoord,
    RegionSnapshot,
    WorldRegion,
    WorldState,
)
from world_api.interpreter import RulesInterpreter  # noqa: E402
from world_api.regions import GENERATOR_VERSION, generate_region, region_of  # noqa: E402
from world_api.worldspec import build_spec  # noqa: E402

PROMPT = "A pine forest on rolling hills around a lake, with boulders, a village on the east shore and a campfire"
SEED = 20261114
RADIUS = 3  # regions in each direction around the spawn region
STAMP = datetime(2026, 11, 14, 20, 0, 0, tzinfo=timezone.utc)


def main() -> int:
    draft = RulesInterpreter().world(PROMPT)
    # The keyword interpreter picks one tree kind; add the other so the sample shows every archetype.
    from world_api.worldspec import FeatureDraft

    draft.features.append(FeatureDraft(archetype="tree.broadleaf", placement="lowlands", density_per_hectare=25.0))
    spec = build_spec(draft, PROMPT, SEED)
    spec.interpretation_notes.insert(0, "offline sample generated by scripts/export_sample_world.py (rules interpreter)")
    world = WorldState(
        world_id="sample-offline", name=spec.title, seed=SEED, revision=1, generator_version=GENERATOR_VERSION,
        spec=spec, environment=spec.environment, gameplay=GameplayState(),
        player=PlayerState(player_id="p1", position=spec.spawn), status=GenerationStatus.geometry_ready,
        created_at=STAMP, updated_at=STAMP,
    )
    here = region_of(spec.spawn[0], spec.spawn[2])
    regions = []
    total = 0
    for dx in range(-RADIUS, RADIUS + 1):
        for dz in range(-RADIUS, RADIUS + 1):
            coord = RegionCoord(rx=here.rx + dx, rz=here.rz + dz)
            entities = generate_region(world.world_id, spec, SEED, coord)
            total += len(entities)
            regions.append(RegionSnapshot(
                region=WorldRegion(world_id=world.world_id, coord=coord, revision=0, materialized=True,
                                   generator_version=GENERATOR_VERSION),
                entities=entities,
            ))
    # Show state-driven rendering in the offline sample: mark the tree nearest to spawn as burning and the
    # next one as charred, exactly as the simulation would write them.
    trees = sorted(
        (e for r in regions for e in r.entities if e.kind == "tree"),
        key=lambda e: (e.transform.position[0] - spec.spawn[0]) ** 2 + (e.transform.position[2] - spec.spawn[2]) ** 2,
    )
    if len(trees) >= 4:
        trees[2].state.condition = Condition.burning
        trees[2].state.burn_intensity = 0.35
        trees[2].geometry_params["burn"] = 0.2
        trees[3].state.condition = Condition.charred
        trees[3].geometry_params["burn"] = 1.0
        trees[3].geometry_params["canopy"] = 0.25
    out = {
        "kind": "greality-offline-sample",
        "world": world.model_dump(mode="json"),
        "regions": [r.model_dump(mode="json") for r in regions],
    }
    path = ROOT / "apps" / "web" / "public" / "sample-world.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(out, separators=(",", ":"), sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    kinds: dict[str, int] = {}
    for r in regions:
        for e in r.entities:
            kinds[e.kind] = kinds.get(e.kind, 0) + 1
    print(f"wrote {path.relative_to(ROOT)}: {len(regions)} regions, {total} entities {kinds}, "
          f"{path.stat().st_size / 1024:.0f} KiB, spawn {tuple(round(c, 1) for c in spec.spawn)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
