/**
 * Public static deployment (Vercel): the page is neither served from loopback (companion release, Vite dev) nor paired
 * with a companion. It then never probes the loopback companion (browsers ask for local-network permission) and offers
 * the read-only sample world and the Windows download instead.
 */
export function isPublicSite(pairing: Pairing): boolean {
  const host = window.location.hostname;
  return !pairing.token && !["localhost", "127.0.0.1", "[::1]", "::1"].includes(host);
}

export class Companion {
  constructor(readonly pairing: Pairing) {}

  private async request<T>(path: string, init?: RequestInit, timeoutMs = 60_000): Promise<T> {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);
    let response: Response;
    try {
      response = await fetch(this.pairing.url + path, {
        ...init,
        signal: controller.signal,
        headers: {
          "Content-Type": "application/json",
          ...(this.pairing.token ? { Authorization: `Bearer ${this.pairing.token}` } : {}),
        },
      });
    } catch (error) {
      throw new ApiFailure(0, "unreachable", `Companion not reachable at ${this.pairing.url} (${(error as Error).name}).`);
    } finally {
      clearTimeout(timer);
    }
    if (!response.ok) {
      let code = `http_${response.status}`;
      let message = response.statusText;
      try {
        const body = await response.json();
        const detail = body.detail ?? body;
        code = detail.code ?? code;
        message = detail.message ?? message;
      } catch {
        /* non-JSON error body */
      }
      throw new ApiFailure(response.status, code, message);
    }
    return (await response.json()) as T;
  }

  health(): Promise<HealthReport> {
    return this.request<HealthReport>("/v1/health", undefined, 4000);
  }
  listWorlds(): Promise<WorldSummary[]> {
    return this.request<WorldSummary[]>("/v1/worlds");
  }
  getWorld(id: string): Promise<WorldState> {
    return this.request<WorldState>(`/v1/worlds/${encodeURIComponent(id)}`);
  }
  /** offline=true uses the server's keyword interpreter instead of Gemini (labelled as such in the world). */
  createWorld(prompt: string, offline = false): Promise<WorldState> {
    return this.request<WorldState>("/v1/worlds", { method: "POST", body: JSON.stringify({ prompt, offline }) }, 480_000);
  }
  command(cmd: WorldCommand, timeoutMs = 30_000): Promise<MutationResult> {
    return this.request<MutationResult>(`/v1/worlds/${encodeURIComponent(cmd.world_id)}/commands`, { method: "POST", body: JSON.stringify(cmd) }, timeoutMs);
  }
  sync(worldId: string, afterRevision: number): Promise<WorldSync> {
    return this.request<WorldSync>(`/v1/worlds/${encodeURIComponent(worldId)}/sync?after_revision=${afterRevision}`, undefined, 15_000);
  }
  putPlayer(worldId: string, player: PlayerState): Promise<unknown> {
    return this.request(`/v1/worlds/${encodeURIComponent(worldId)}/player`, { method: "PUT", body: JSON.stringify(player) }, 10_000);
  }
  /** One map of a CC0 texture set (served from the companion's Neon cache, fetched from Poly Haven on first use). */
  async fetchTexture(assetId: string, map: "albedo" | "normal" | "arm" | "height"): Promise<Blob> {
    const response = await fetch(`${this.pairing.url}/v1/textures/${encodeURIComponent(assetId)}/${map}`, {
      headers: this.pairing.token ? { Authorization: `Bearer ${this.pairing.token}` } : {},
    });
    if (!response.ok) throw new ApiFailure(response.status, `http_${response.status}`, `texture ${assetId}/${map}`);
    return response.blob();
  }
  /** Bytes of a published Gaussian asset (the caller verifies sha256 and region revision before use). */
  async fetchAsset(assetId: string): Promise<ArrayBuffer> {
    const response = await fetch(`${this.pairing.url}/v1/assets/${encodeURIComponent(assetId)}`, {
      headers: this.pairing.token ? { Authorization: `Bearer ${this.pairing.token}` } : {},
    });
    if (!response.ok) throw new ApiFailure(response.status, `http_${response.status}`, `asset ${assetId}: ${response.statusText}`);
    return response.arrayBuffer();
  }
  loadRegions(id: string, coords: RegionCoord[]): Promise<RegionSnapshot[]> {
    return this.request<RegionSnapshot[]>(`/v1/worlds/${encodeURIComponent(id)}/regions:batch`, {
      method: "POST",
      body: JSON.stringify({ coords }),
    });
  }
}

export async function loadOfflineSample(): Promise<OfflineSample> {
  const response = await fetch(`${import.meta.env.BASE_URL}sample-world.json`);
  if (!response.ok) throw new ApiFailure(response.status, "sample_missing", "Offline sample world is not available.");
  return (await response.json()) as OfflineSample;
}
