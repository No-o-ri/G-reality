/**
 * Companion client. The companion URL and pairing token arrive in the URL fragment
 * (`#companion=http://127.0.0.1:8765&token=…`, printed by the companion at start-up) and are kept in
 * sessionStorage for the tab only. No database credential ever reaches the browser.
 */
import type { HealthReport, MutationResult, PlayerState, RegionCoord, RegionSnapshot, WorldCommand, WorldState, WorldSync } from "@contracts";

export interface WorldSummary {
  world_id: string;
  name: string;
  seed: number;
  revision: number;
  status: string;
  generator_version: number;
  created_at: string;
}

export interface OfflineSample {
  kind: "greality-offline-sample";
  world: WorldState;
  regions: RegionSnapshot[];
}

/** Worlds generated by an older terrain function are not rendered (their entity heights would not match). */
export const MIN_RENDERABLE_GENERATOR_VERSION = 2;

export class ApiFailure extends Error {
  constructor(
    public status: number,
    public code: string,
    message: string,
  ) {
    super(message);
  }
}

const KEY = "greality.companion";

export interface Pairing {
  url: string;
  token: string;
}

export function readPairing(): Pairing {
  const hash = new URLSearchParams(window.location.hash.replace(/^#/, ""));
  const fromHash = hash.get("token");
  if (fromHash) {
    const pairing = { url: hash.get("companion") ?? defaultUrl(), token: fromHash };
    sessionStorage.setItem(KEY, JSON.stringify(pairing));
    // remove the token from the address bar
    history.replaceState(null, "", window.location.pathname + window.location.search);
    return pairing;
  }
  try {
    const stored = JSON.parse(sessionStorage.getItem(KEY) ?? "null") as Pairing | null;
    if (stored?.url && stored.token) return stored;
  } catch {
    /* ignore malformed storage */
  }
  return { url: defaultUrl(), token: "" };
}

function defaultUrl(): string {
  return (import.meta.env.VITE_COMPANION_URL as string | undefined) ?? "http://127.0.0.1:8765";
}

